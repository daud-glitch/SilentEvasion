def style_document(doc):
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(10.5)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15
    for name, size in (("Heading 1", 14), ("Heading 2", 12), ("Heading 3", 11)):
        st = doc.styles[name]
        st.font.name = "Times New Roman"
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = RGBColor(0, 0, 0)


def meta_from_main():
    main_tex = open(os.path.join(PAPER, "main.tex"), encoding="utf-8").read()
    title = take_group(main_tex, re.search(r"\\title\{", main_tex).end() - 1)[0]
    author = take_group(main_tex, re.search(r"\\author\{", main_tex).end() - 1)[0]
    inst = take_group(main_tex, re.search(r"\\institution\{", main_tex).end() - 1)[0]
    city = take_group(main_tex, re.search(r"\\city\{", main_tex).end() - 1)[0]
    country = take_group(main_tex, re.search(r"\\country\{", main_tex).end() - 1)[0]
    kw = take_group(main_tex, re.search(r"\\keywords\{", main_tex).end() - 1)[0]
    mail = re.search(r"\\email\{", main_tex)
    email = take_group(main_tex, mail.end() - 1)[0] if mail else ""
    body = main_tex.split("\\maketitle", 1)[1]
    body = body.split("\\bibliographystyle", 1)[0]
    return dict(title=title, author=author, institution=inst, city=city,
                country=country, keywords=kw, email=email, body=body)


def body_order(body_text):
    """The list of section files in the order main.tex includes them."""
    order = []
    for m in re.finditer(r"\\input\{([^}]+)\}", body_text):
        rel = m.group(1)
        path = os.path.join(PAPER, rel if rel.endswith(".tex") else rel + ".tex")
        if os.path.exists(path):
            order.append(path)
    return order


def collect_blocks(paths):
    blocks = []
    for path in paths:
        text = expand_includes(strip_comments(open(path, encoding="utf-8").read()), path)
        blocks += parse_tex(text)
    return blocks


def env_blocks(blocks, kind):
    """Split out non-paragraph environments so they can be emitted in place."""
    return blocks


def add_paragraph(doc, block, labels, cites, unknown, style=None):
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    add_runs(para, inline_runs(squash(block["text"]), labels, cites,
                               style or {}, unknown))


def add_list(doc, block, labels, cites, unknown, ordered=False):
    items = re.split(r"\\item", block["body"])[1:]
    for item in (squash(i) for i in items):
        para = doc.add_paragraph(style="List Number" if ordered else "List Bullet")
        add_runs(para, inline_runs(item, labels, cites, {}, unknown))


def add_equation(doc, block, labels, cites, unknown):
    lines = [squash(l) for l in block["body"].split("\\\\") if l.strip()]
    for line in lines:
        para = doc.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        add_runs(para, inline_runs(line, labels, cites, {"italic": True}, unknown))
    if block["number"]:
        num = doc.add_paragraph()
        num.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        run = num.add_run("(%d)" % block["number"])
        run.italic = True


def parse_bib(path):
    entries = {}
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r"@(\w+)\{([^,]+),(.*?)\n\}\n", text, re.S):
        kind, key, body = m.group(1), m.group(2), m.group(3)
        fields = {}
        for fm in re.finditer(r"(\w+)\s*=\s*\{(.*?)\},?\n", body, re.S):
            fields[fm.group(1).lower()] = " ".join(fm.group(2).split())
        entries[key] = dict(kind=kind, **fields)
    return entries


def add_references(doc, cites, bib, labels, unknown):
    doc.add_heading("References", level=1)
    for key, num in sorted(cites.items(), key=lambda kv: kv[1]):
        e = bib.get(key)
        if not e:
            raise TexError("no bibliography entry for %s" % key)
        author = e.get("author", "").replace(" and ", ", ")
        title = e.get("title", "").strip("{}")
        venue = e.get("journal") or e.get("booktitle") or e.get("publisher", "")
        bits = ["[%d]" % num, author, title + ".", venue]
        if e.get("volume"):
            bits.append("vol. %s" % e["volume"])
        if e.get("number"):
            bits.append("no. %s" % e["number"])
        if e.get("pages"):
            bits.append("pp. %s" % e["pages"].replace("--", "\u2013"))
        bits.append(e.get("year", ""))
        if e.get("doi"):
            bits.append("doi:%s" % e["doi"])
        para = doc.add_paragraph()
        para.paragraph_format.space_after = Pt(2)
        add_runs(para, inline_runs(" ".join(b for b in bits if b).replace("..", "."),
                                   labels, cites, {"small": True}, unknown))


def main():
    meta = meta_from_main()
    doc = Document()
    style_document(doc)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_runs(title, inline_runs(meta["title"], {}, {}, {"bold": True}))
    for run in title.runs:
        run.font.size = Pt(18)

    author = doc.add_paragraph()
    author.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_runs(author, inline_runs(meta["author"], {}, {}, {}))
    for run in author.runs:
        run.font.size = Pt(12)
        run.bold = True

    aff = doc.add_paragraph()
    aff.alignment = WD_ALIGN_PARAGRAPH.CENTER
    add_runs(aff, inline_runs("%s, %s, %s" % (meta["institution"], meta["city"],
                                             meta["country"]), {}, {}, {"italic": True}))

    if meta["email"]:
        mail = doc.add_paragraph()
        mail.alignment = WD_ALIGN_PARAGRAPH.CENTER
        add_runs(mail, inline_runs(meta["email"], {}, {}, {}))
        for run in mail.runs:
            run.font.size = Pt(10)

    unknown = []

    # Abstract is unnumbered and comes from its own file, exactly as the PDF does.
    abstract_blocks = collect_blocks([os.path.join(SECTIONS, "00_abstract.tex")])
    labels, cites = number_blocks(abstract_blocks)
    doc.add_heading("Abstract", level=1)
    for b in abstract_blocks:
        add_paragraph(doc, b, labels, cites, unknown)

    kw = doc.add_paragraph()
    add_runs(kw, inline_runs("Keywords: " + meta["keywords"], {}, {}, {"italic": True}))

    blocks = collect_blocks(body_order(meta["body"]))
    number_blocks(blocks, labels, cites)

    for b in blocks:
        kind = b["kind"]
        if kind == "section":
            doc.add_heading("%d. %s" % (b["number"],
                                        plain_text(b["text"])), level=1)
        elif kind == "subsection":
            doc.add_heading("%s %s" % (b["number"], plain_text(b["text"])), level=2)
        elif kind == "paragraph":
            doc.add_heading(plain_text(b["text"]), level=3)
        elif kind == "p":
            add_paragraph(doc, b, labels, cites, unknown)
        elif kind == "env":
            env = b["env"]
            if env.startswith("table"):
                add_table(doc, b, labels, cites, unknown)
            elif env.startswith("figure"):
                add_figure(doc, b, labels, cites, unknown)
            elif env == "itemize":
                add_list(doc, b, labels, cites, unknown, ordered=False)
            elif env == "enumerate":
                add_list(doc, b, labels, cites, unknown, ordered=True)
            elif env == "equation":
                add_equation(doc, b, labels, cites, unknown)
            else:
                raise TexError("unhandled environment %s" % env)

    bib = parse_bib(os.path.join(PAPER, "refs.bib"))
    add_references(doc, cites, bib, labels, unknown)

    if unknown:
        raise TexError("unhandled macros would have been dropped:\n  %s"
                       % "\n  ".join(sorted(set(unknown))))

    doc.save(OUT)
    print("wrote %s" % OUT)
    print("%d sections, %d tables, %d figures, %d citations"
          % (len([b for b in blocks if b["kind"] == "section"]),
             len([b for b in blocks if b["kind"] == "env" and b["env"].startswith("table")]),
             len([b for b in blocks if b["kind"] == "env" and b["env"].startswith("figure")]),
             len(cites)))
    return 0


def plain_text(tex):
    """A heading's text without formatting, for use as a Word heading."""
    return squash("".join(t for t, _ in inline_runs(tex, {}, {}, {})))


if __name__ == "__main__":
    sys.exit(main())
