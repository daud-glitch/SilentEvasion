"""
Build paper/main.docx from the same sources the PDF is built from.

    python src/make_docx.py

Why a converter instead of pandoc: the tables in this paper are generated by
src/make_paper_tex.py as booktabs tabular, and the sections use a small, fixed
set of macros (\\section, \\paragraph, \\textbf, \\emph, \\ref, \\cite, a handful
of math symbols). That is a small enough language to parse exactly, and parsing
it here means the Word file and the PDF cannot disagree about a table, because
both read the same .tex and the same CSVs underneath it.

What the converter guarantees:
  * section order comes from main.tex, so the docx cannot drift from the paper;
  * every table and figure is a real Word table / inline image, not an image of
    a table;
  * \\ref and \\cite are resolved with the same numbering LaTeX would use
    (floats numbered in order of appearance, citations in order of first use);
  * nothing silently disappears: an unknown macro raises instead of being
    dropped, and tests/check_docx.py re-reads the .docx and audits what landed.

Writes paper/main.docx.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from docx import Document                                    # noqa: E402
from docx.enum.text import WD_ALIGN_PARAGRAPH               # noqa: E402
from docx.shared import Inches, Pt, RGBColor                # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.path.join(ROOT, "paper")
SECTIONS = os.path.join(PAPER, "sections")
TABLES = os.path.join(PAPER, "tables")
FIGURES = os.path.join(PAPER, "figures")
OUT = os.path.join(PAPER, "main.docx")

# Math and symbol macros, mapped to what a reader should see in Word. A missing
# entry is a hard error on purpose: a silently dropped glyph is worse than a
# failed build.
UNICODE = {
    "S": "\u00a7", "dag": "\u2020", "dagger": "\u2020", "times": "\u00d7",
    "rightarrow": "\u2192", "to": "\u2192", "ldots": "\u2026", "dots": "\u2026",
    "tau": "\u03c4", "alpha": "\u03b1", "phi": "\u03c6", "beta": "\u03b2",
    "frac12": "\u00bd", "mid": "\u2223", "qquad": " ", "quad": " ",
    "le": "\u2264", "ge": "\u2265", "approx": "\u2248", "pm": "\u00b1",
    "textemdash": "\u2014", "textendash": "\u2013", "ldots": "\u2026",
    "cmark": "\u2713",
}

FORMAT = {"textbf": "bold", "emph": "italic", "textit": "italic",
          "textsl": "italic", "texttt": "mono", "textsc": "smallcaps"}

# Accents in the bibliography ({\c S}erban, Vor{\'a}{\v c}ek) are two-character
# commands, so they have to be read before the one-character escape table below
# or the mark and the letter come out as two separate characters.
ACCENTS = {"'": "\u0301", "`": "\u0300", "^": "\u0302", '"': "\u0308",
           "~": "\u0303", "=": "\u0304", ".": "\u0307", "c": "\u0327",
           "v": "\u030c", "u": "\u0306", "H": "\u030b", "k": "\u0328",
           "r": "\u030a", "b": "\u0331", "d": "\u0323"}
ACCENT_CMDS = {"c", "v", "u", "H", "k", "r", "b", "d"}

IGNORED = {"centering", "small", "footnotesize", "scriptsize", "normalsize",
           "noindent", "newpage", "clearpage", "maketitle", "bfseries",
           "itshape", "ttfamily", "vspace", "hspace", "columnwidth",
           "textwidth", "linewidth", "par", "relax", "hfill", "bigskip",
           "medskip", "smallskip", "protect", "hline", "toprule", "midrule",
           "bottomrule", "cmidrule"}


class TexError(Exception):
    pass


# ── lexing helpers ──────────────────────────────────────────────────────────


def strip_comments(text):
    """Remove LaTeX comments but keep an escaped percent sign."""
    out = []
    for line in text.split("\n"):
        i = 0
        while i < len(line):
            if line[i] == "\\" and i + 1 < len(line):
                i += 2
                continue
            if line[i] == "%":
                line = line[:i]
                break
            i += 1
        out.append(line)
    return "\n".join(out)


def take_group(text, i):
    """Read a {...} group starting at or after index i; return (content, end).

    Handles nesting, which matters for \\textbf{a \\emph{b} c} and for
    \\multicolumn{2}{l}{text}.
    """
    while i < len(text) and text[i] in " \n\t":
        i += 1
    if i >= len(text) or text[i] != "{":
        raise TexError("expected '{' at %r" % text[i:i + 40])
    depth = 0
    start = i + 1
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start:i], i + 1
        i += 1
    raise TexError("unbalanced braces near %r" % text[start:start + 40])


def take_optional(text, i):
    """Read a [...] optional argument if present; return (content, end)."""
    while i < len(text) and text[i] in " \n\t":
        i += 1
    if i < len(text) and text[i] == "[":
        end = text.find("]", i)
        if end > 0:
            return text[i + 1:end], end + 1
    return None, i


def expand_includes(text, base):
    """Resolve \\input and the \\IfFileExists{g}{body}{} gate the paper uses.

    Doing this before parsing means the docx has exactly the sections the PDF
    has: a results section whose CSV was deleted is absent from both.
    """
    # \IfFileExists{tables/t5_transfer.tex}{\input{...}}{}. The three groups are
    # consumed together: replacing only the macro name would leave the body in
    # place and duplicate every gated section and figure.
    while True:
        idx = text.find("\\IfFileExists{")
        if idx < 0:
            break
        arg, i = take_group(text, idx + len("\\IfFileExists"))
        body, i = take_group(text, i)
        other, i = take_group(text, i)
        target = os.path.join(PAPER, arg)
        text = text[:idx] + (body if os.path.exists(target) else other) + text[i:]

    for _ in range(6):                              # nested inputs, bounded
        m = re.search(r"\\input\{([^}]*)\}", text)
        if not m:
            break
        rel = m.group(1)
        path = os.path.join(PAPER, rel if rel.endswith(".tex") else rel + ".tex")
        if not os.path.exists(path):
            raise TexError("\\input{%s} does not resolve" % rel)
        with open(path, encoding="utf-8") as f:
            body = strip_comments(f.read())
        text = text[:m.start()] + body + text[m.end():]
    return text


# ── block parsing ───────────────────────────────────────────────────────────


def split_paragraphs(text):
    """Paragraphs are separated by a blank line; \\par does the same."""
    text = text.replace("\\par", "\n\n")
    chunks = re.split(r"\n[ \t]*\n", text)
    return [c.strip() for c in chunks if c.strip()]


def find_env_end(text, i, env):
    """Index of the \\end{env} matching the \\begin at i (same-env nesting)."""
    depth = 1
    pos = i
    needle_begin = "\\begin{%s}" % env
    needle_end = "\\end{%s}" % env
    while depth:
        nb = text.find(needle_begin, pos)
        ne = text.find(needle_end, pos)
        if ne < 0:
            raise TexError("unterminated %s" % env)
        if 0 <= nb < ne:
            depth += 1
            pos = nb + len(needle_begin)
        else:
            depth -= 1
            pos = ne + len(needle_end)
    return ne


def parse_tex(text):
    """Turn one .tex file (includes expanded) into a list of blocks."""
    blocks = []
    i = 0
    head = re.compile(r"\\(section|subsection|paragraph)\*?\{")
    while i < len(text):
        m = head.search(text, i)
        b = text.find("\\begin{", i)
        cands = [p for p in (m.start() if m else -1, b) if p >= 0]
        nxt = min(cands) if cands else -1
        chunk = text[i:nxt] if nxt >= 0 else text[i:]
        for para in split_paragraphs(chunk):
            label = None
            lm = re.search(r"\\label\{([^}]+)\}", para)
            if lm:
                label = lm.group(1)
                para = (para[:lm.start()] + para[lm.end():]).strip()
            # A label on its own line belongs to the heading above it, and the
            # heading may be the only thing in the chunk, so this has to happen
            # before the empty-paragraph test or the label is silently lost.
            if blocks and label and blocks[-1]["kind"] in ("section", "subsection"):
                blocks[-1]["label"] = label
                continue
            if not para:
                continue
            blocks.append({"kind": "p", "text": para, "label": label})
        if nxt < 0:
            break
        if m and nxt == m.start():
            kind = m.group(1)
            content, j = take_group(text, m.end() - 1)
            blocks.append({"kind": kind, "text": content, "label": None})
            i = j
            continue
        env, j = take_group(text, b + len("\\begin"))
        end = find_env_end(text, j, env)
        body = text[j:end]
        if env == "abstract":
            # The abstract environment is a container, not a float: its contents
            # are ordinary paragraphs and must not be emitted as a block of
            # their own or the text would be lost.
            blocks += parse_tex(body)
        else:
            blocks.append({"kind": "env", "env": env, "body": body})
        i = end + len("\\end{%s}" % env)
    return blocks


# ── numbering pass ──────────────────────────────────────────────────────────


def number_blocks(blocks, labels=None, cites=None):
    """Assign section/float/citation numbers in order of appearance.

    This is the same rule LaTeX uses: floats are numbered by where they appear,
    citations by where they are first used. It is done in a separate pass
    because the text refers to tables and sections that appear later.
    """
    labels = {} if labels is None else labels
    cites = {} if cites is None else cites
    sec = sub = tbl = fig = eq = 0
    for b in blocks:
        kind = b["kind"]
        if kind == "section":
            sec += 1
            sub = 0
            b["number"] = sec
            if b.get("label"):
                labels[b["label"]] = sec
        elif kind == "subsection":
            sub += 1
            b["number"] = "%d.%d" % (sec, sub)
            if b.get("label"):
                labels[b["label"]] = b["number"]
        elif kind == "p":
            if b.get("label"):
                labels[b["label"]] = "%d.%d" % (sec, sub) if sub else sec
            for m in re.finditer(r"\\cite\{([^}]+)\}", b["text"]):
                for key in (k.strip() for k in m.group(1).split(",")):
                    if key and key not in cites:
                        cites[key] = len(cites) + 1
        elif kind == "env":
            env = b["env"]
            if env.startswith("table"):
                tbl += 1
                b["number"] = tbl
            elif env.startswith("figure"):
                fig += 1
                b["number"] = fig
            elif env == "equation":
                eq += 1
                b["number"] = eq
            lm = re.search(r"\\label\{([^}]+)\}", b["body"])
            if lm and b["number"] is not None:
                labels[lm.group(1)] = b["number"]
            for m in re.finditer(r"\\cite\{([^}]+)\}", b["body"]):
                for key in (k.strip() for k in m.group(1).split(",")):
                    if key and key not in cites:
                        cites[key] = len(cites) + 1
    return labels, cites


# ── inline rendering ────────────────────────────────────────────────────────

PLAIN = re.compile(r"[^\\{}_^~`'$\-]+")


def inline_runs(text, labels, cites, style=None, unknown=None):
    """Convert inline LaTeX into [(text, style)] runs."""
    style = style or {}
    out = []
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\":
            nxt = text[i + 1] if i + 1 < len(text) else ""
            mark = after = None
            if nxt in ACCENTS and not nxt.isalpha():
                mark, after = ACCENTS[nxt], i + 2
            else:
                # A letter accent is exactly one letter: \c S and \v c are
                # accents, \ref and \rightarrow are not, and reading "\r" as
                # an accent is how \ref{...} turned into a ring over an e.
                am = re.match(r"\\([a-zA-Z])(?![a-zA-Z])", text[i:])
                if am and am.group(1) in ACCENT_CMDS:
                    mark, after = ACCENTS[am.group(1)], i + 2
            if mark:
                if after < len(text) and text[after] == "{":
                    arg, k = take_group(text, after)
                else:
                    k = after + 1 if after < len(text) and text[after] == " " else after
                    arg, k = text[k:k + 1], k + 1
                inner = inline_runs(arg, labels, cites, style, unknown)
                if inner:
                    inner[0] = (inner[0][0] + mark, inner[0][1])
                else:
                    inner = [(mark, style)]
                out += inner
                i = k
                continue
            if i + 1 < len(text) and not text[i + 1].isalpha():
                nxt = text[i + 1]
                mapping = {"%": "%", "&": "&", "_": "_", "#": "#", "$": "$",
                           "{": "{", "}": "}", " ": " ", ",": " ", ";": " ",
                           ":": " ", "!": "", "-": ""}
                out.append((mapping.get(nxt, nxt), style))
                i += 2
                continue
            m = re.match(r"\\([a-zA-Z]+)", text[i:])
            cmd = m.group(1)
            j = i + m.end()
            if cmd in FORMAT:
                arg, j = take_group(text, j)
                sub = dict(style)
                sub[FORMAT[cmd]] = True
                out += inline_runs(arg, labels, cites, sub, unknown)
                i = j
                continue
            if cmd == "textcolor":
                _, j = take_group(text, j)
                arg, j = take_group(text, j)
                out += inline_runs(arg, labels, cites, style, unknown)
                i = j
                continue
            if cmd in ("text", "mathrm", "mbox", "textrm", "textnormal"):
                arg, j = take_group(text, j)
                out += inline_runs(arg, labels, cites, style, unknown)
                i = j
                continue
            if cmd in ("mathbf", "mathit", "mathcal"):
                arg, j = take_group(text, j)
                sub = dict(style)
                sub["bold" if cmd == "mathbf" else "italic"] = True
                out += inline_runs(arg, labels, cites, sub, unknown)
                i = j
                continue
            if cmd in ("ref", "autoref", "cref"):
                arg, j = take_group(text, j)
                num = labels.get(arg)
                if num is None:
                    raise TexError("\\ref{%s} has no label" % arg)
                out.append((str(num), style))
                i = j
                continue
            if cmd in ("cite", "citep", "citet"):
                arg, j = take_group(text, j)
                nums = [cites.get(k.strip()) for k in arg.split(",")]
                missing = [k for k, n in zip(arg.split(","), nums) if n is None]
                if missing:
                    raise TexError("\\cite keys never numbered: %s" % missing)
                out.append(("[%s]" % ", ".join(str(n) for n in nums), style))
                i = j
                continue
            if cmd == "url":
                # Word has no \url. The address is rendered as plain text (never
                # dropped: an unhandled macro aborts the build, which is how
                # the availability section's link was caught in the first
                # place). LaTeX treats the argument as verbatim, so the only
                # escapes that can appear are \_ and \%.
                arg, j = take_group(text, j)
                out.append((arg.replace("\\_", "_").replace("\\%", "%"), style))
                i = j
                continue
            if cmd == "tilde":
                arg, j = take_group(text, j)
                inner = inline_runs(arg, labels, cites, style, unknown)
                if inner:
                    inner[-1] = (inner[-1][0] + "\u0303", inner[-1][1])
                out += inner
                i = j
                continue
            if cmd in ("tfrac", "frac", "dfrac"):
                a, j = take_group(text, j)
                b, j = take_group(text, j)
                out += inline_runs(a, labels, cites, style, unknown)
                out.append(("/", style))
                out += inline_runs(b, labels, cites, style, unknown)
                i = j
                continue
            if cmd == "label":
                _, j = take_group(text, j)
                i = j
                continue
            if cmd == "includegraphics":
                _, j = take_optional(text, j)
                _, j = take_group(text, j)
                i = j
                continue
            if cmd in UNICODE:
                out.append((UNICODE[cmd], style))
                i = j
                continue
            if cmd in IGNORED:
                # commands that carry an argument we do not render
                i = j
                if cmd in ("vspace", "hspace") and i < len(text) and text[i] == "{":
                    _, i = take_group(text, i)
                continue
            if unknown is not None:
                # Keep the context: an unhandled macro is a build error, and
                # "\\c" alone does not say where it came from.
                unknown.append("%s ... %s" % (cmd.strip(),
                                               text[max(0, i - 40):i + 40].replace("\n", " ")))
                
            i = j
            continue
        if c == "$":
            # Inline math: rendered italic, with the delimiters gone. A stray
            # unmatched $ is passed through rather than eating the paragraph.
            end = text.find("$", i + 1)
            if end < 0:
                out.append(("$", style))
                i += 1
                continue
            sub = dict(style)
            sub["italic"] = True
            out += inline_runs(text[i + 1:end], labels, cites, sub, unknown)
            i = end + 1
            continue
        if c == "{":
            i += 1
            continue
        if c == "}":
            i += 1
            continue
        if c in "_^":
            if i + 1 < len(text) and text[i + 1] == "{":
                arg, j = take_group(text, i + 1)
            else:
                arg, j = text[i + 1:i + 2], i + 2
            sub = dict(style)
            sub["sub" if c == "_" else "sup"] = True
            out += inline_runs(arg, labels, cites, sub, unknown)
            i = j
            continue
        if c == "~":
            out.append((" ", style))
            i += 1
            continue
        if text[i:i + 3] == "---":
            out.append(("\u2014", style))
            i += 3
            continue
        if text[i:i + 2] == "--":
            out.append(("\u2013", style))
            i += 2
            continue
        if text[i:i + 2] == "``":
            out.append(("\u201c", style))
            i += 2
            continue
        if text[i:i + 2] == "''":
            out.append(("\u201d", style))
            i += 2
            continue
        if c == "`":
            out.append(("\u2018", style))
            i += 1
            continue
        if c == "'":
            out.append(("\u2019", style))
            i += 1
            continue
        m = PLAIN.match(text, i)
        if m:
            out.append((m.group(0), style))
            i = m.end()
            continue
        out.append((c, style))
        i += 1
    return out


def squash(text):
    """Collapse the source's line wrapping so Word does not inherit it.

    The .tex files are hard-wrapped at ~78 columns; carrying those newlines and
    their indentation into a run leaves doubled spaces inside sentences.
    """
    return re.sub(r"\s+", " ", text).strip()


def add_runs(paragraph, runs):
    """Write runs, collapsing whitespace across run boundaries.

    Squashing the source line is not enough: \\text{ with word } carries a
    leading and trailing space of its own, so a styled run can still leave two
    spaces next to the plain text around it.
    """
    prev_space = False
    for text, style in runs:
        text = re.sub(r"[ \t]+", " ", text)
        if prev_space and text.startswith(" "):
            text = text[1:]
        if not text:
            continue
        prev_space = text.endswith(" ")
        run = paragraph.add_run(text)
        run.bold = bool(style.get("bold"))
        run.italic = bool(style.get("italic"))
        if style.get("mono"):
            run.font.name = "Consolas"
        if style.get("sub"):
            run.font.subscript = True
        if style.get("sup"):
            run.font.superscript = True


# ── tables and figures ──────────────────────────────────────────────────────


def split_rows(body):
    """Rows of a tabular: split on \\\\, keeping the cell text intact."""
    body = body.replace("\\hline", "")
    rows = []
    for m in re.finditer(r"(?:^|\\\\)(.*?)(?=\\\\|$)", body, re.S):
        row = m.group(1)
        for rule in ("\\toprule", "\\midrule", "\\bottomrule"):
            row = row.replace(rule, "")
        if row.strip():
            rows.append(row.strip())
    return rows


def split_cells(row):
    """Cells of a row, honouring braces so a {a & b} group does not split."""
    cells, depth, cur = [], 0, []
    i = 0
    while i < len(row):
        ch = row[i]
        if ch == "\\":
            cur.append(row[i:i + 2])
            i += 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "&" and depth == 0:
            cells.append("".join(cur).strip())
            cur = []
            i += 1
            continue
        cur.append(ch)
        i += 1
    cells.append("".join(cur).strip())
    return cells


def parse_table(body):
    cap = re.search(r"\\caption\{", body)
    caption = take_group(body, cap.end() - 1)[0] if cap else ""
    tab = re.search(r"\\begin\{tabular\}\{[^}]*\}", body)
    if not tab:
        raise TexError("table without tabular")
    start = tab.end()
    end = body.find("\\end{tabular}", start)
    rows = []
    for raw in split_rows(body[start:end]):
        cells = split_cells(raw)
        span = 1
        m = re.match(r"\\multicolumn\{(\d+)\}\{[^}]*\}\{", cells[0])
        if m:
            span = int(m.group(1))
            inner = take_group(cells[0], m.end() - 1)[0]
            cells = [inner] + cells[1:]
        rows.append((cells, span))
    return caption, rows


def add_table(doc, block, labels, cites, unknown):
    caption, rows = parse_table(block["body"])
    if not rows:
        raise TexError("empty table")
    # A row with a \multicolumn{n} occupies n columns but lists one fewer cell
    # for every span, so the table's width is not len(cells).
    ncols = max((len(c) - 1 + s) for c, s in rows)
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = para.add_run("Table %d. " % block["number"])
    run.bold = True
    run.font.size = Pt(9)
    add_runs(para, inline_runs(squash(caption), labels, cites,
                               {"italic": True}, unknown))
    for r in para.runs[1:]:
        r.font.size = Pt(9)

    table = doc.add_table(rows=len(rows), cols=ncols)
    table.style = "Table Grid"
    for r, (cells, span) in enumerate(rows):
        row = table.rows[r]
        col = 0
        for idx, cell_text in enumerate(cells):
            # Walk columns, not cells: the spanning cell consumes `span` columns
            # and everything after it shifts right by that much. Indexing by
            # cell number instead loses the value after a \multicolumn.
            width = span if idx == 0 else 1
            cell = row.cells[col]
            if width > 1:
                cell = cell.merge(row.cells[col + width - 1])
            col += width
            cell.text = ""
            p = cell.paragraphs[0]
            add_runs(p, inline_runs(cell_text, labels, cites,
                                    {"bold": r == 0}, unknown))
            for run in p.runs:
                run.font.size = Pt(8.5)
    fit_widths(table, rows)
    doc.add_paragraph()


def fit_widths(table, rows):
    """Give each column a width proportional to its content.

    python-docx creates equal-width columns, which wraps a model name over
    three lines while the numeric columns sit half empty. Widths are estimated
    from the longest cell in each column and scaled to the text block.
    """
    ncols = len(table.columns)
    longest = [4] * ncols
    for cells, span in rows:
        col = 0
        for idx, text in enumerate(cells):
            width = span if idx == 0 else 1
            plain = "".join(t for t, _ in inline_runs(text, {}, {}, {}))
            if col < ncols:
                longest[col] = max(longest[col], min(len(plain), 24))
            col += width
    # A short header like "ASR" must not collapse to a column narrower than the
    # word, so every column gets padding and a floor before the rest is scaled.
    weights = [n + 3 for n in longest]
    avail = 6.4
    widths = [avail * w / sum(weights) for w in weights]
    floor = 0.55
    for _ in range(3):
        short = [i for i, w in enumerate(widths) if w < floor - 1e-9]
        if not short:
            break
        for i in short:
            widths[i] = floor
        rest = [i for i in range(ncols) if i not in short]
        free = avail - floor * len(short)
        total = sum(weights[i] for i in rest) or 1
        for i in rest:
            widths[i] = free * weights[i] / total
    table.autofit = False
    for c, inches in enumerate(widths):
        for row in table.rows:
            row.cells[c].width = Inches(inches)


def add_figure(doc, block, labels, cites, unknown):
    m = re.search(r"\\includegraphics", block["body"])
    if m:
        _, j = take_optional(block["body"], m.end())
        path, _ = take_group(block["body"], j)
        missing = "run src/make_figures.py"
    else:
        # A figure drawn in TikZ has no raster in the .tex, so the block names
        # the picture Word should embed with \wordfigure{figures/name}, which
        # is a no-op macro in main.tex.
        hint = re.search(r"\\wordfigure\{([^}]*)\}", block["body"])
        if not hint:
            raise TexError("figure has neither \\includegraphics nor "
                           "\\wordfigure{figures/name}")
        path = hint.group(1).strip()
        missing = "run src/make_pipeline_png.py"
    png = os.path.join(PAPER, path + ".png")
    if not os.path.exists(png):
        raise TexError("missing %s - %s" % (png, missing))
    doc.add_picture(png, width=Inches(6.2))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap = re.search(r"\\caption\{", block["body"])
    caption = take_group(block["body"], cap.end() - 1)[0] if cap else ""
    para = doc.add_paragraph()
    run = para.add_run("Figure %d. " % block["number"])
    run.bold = True
    run.font.size = Pt(9)
    add_runs(para, inline_runs(squash(caption), labels, cites,
                               {"italic": True}, unknown))
    for r in para.runs[1:]:
        r.font.size = Pt(9)


