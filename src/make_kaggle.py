def embed_bootstrap():
    """Bootstrap source with its __main__ guard turned into a call the kernel makes."""
    with open(BOOTSTRAP, "r", encoding="utf-8") as f:
        boot = f.read()
    if BOOTSTRAP_CALL not in boot:
        raise SystemExit("colab_bootstrap.py no longer ends with the __main__ guard; "
                         "update BOOTSTRAP_CALL in src/make_kaggle.py")
    return boot.replace(BOOTSTRAP_CALL,
                        "_BOOTSTRAP_RC = main()\nBOOTSTRAP_RC = _BOOTSTRAP_RC\n")


def build_kernel(models, limit):
    body = embed_bootstrap()
    # /kaggle/working is the ONLY directory Kaggle returns as kernel output, so
    # the project must live there - the bootstrap's default root is /content.
    header = (
        "# Generated by src/make_kaggle.py - do not edit on Kaggle.\n"
        "# Kaggle script kernel: bootstrap -> probe -> baseline -> gate -> attack set.\n"
        "# Regenerate with: python src/make_kaggle.py\n"
        "import os as _os\n"
        "_os.environ.setdefault(\"SLM_ROOT\", \"/kaggle/working\")\n")
    runner = (RUNNER
              .replace("@@MODELS@@", json.dumps(",".join(models)))
              .replace("@@LIMIT@@", json.dumps(limit or "")))
    return header + body + "\n" + runner


def slugify(text):
    """Kaggle derives the kernel slug from the TITLE; build the id the same way
    or the push returns 409 (title resolves to a different id than metadata.id)."""
    out = []
    for ch in text.lower():
        out.append(ch if ch.isalnum() else "-")
    slug = "".join(out)
    while "--" in slug:
        slug = slug.replace("--", "-")
    return slug.strip("-")


SHORT_TAGS = {
    "qwen2.5-3b": "qwen3b",
    "llama3.2-3b": "llama3b",
    "smollm2-1.7b": "smol1.7b",
    "phi3.5-mini": "phi3.5",
}


def build_meta(models, slug=None):
    # Kaggle rejects very long slugs (400) and derives the slug from the title,
    # so the title must stay short and slugifiable.
    tags = [SHORT_TAGS.get(m, m) for m in models]
    title = "SLM robustness %s" % " ".join(tags)
    if slug:
        title = slug.replace("-", " ")
    return {
        "id": "__KAGGLE_USERNAME__/%s" % (slug or slugify(title)),
        "title": title,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="qwen2.5-3b",
                    help="comma-separated keys from src/common.MODELS")
    ap.add_argument("--limit", default=None,
                    help="sample limit per run (omit for the full 800-rows study)")
    ap.add_argument("--slug", default=None,
                    help="kernel slug (default: slugified title, which is what "
                         "Kaggle itself derives)")
    args = ap.parse_args()

    if not os.path.exists(BOOTSTRAP):
        print("missing colab_bootstrap.py -> run: python src/make_bootstrap.py")
        return 1
    models = [m.strip() for m in args.models.split(",") if m.strip()]
    os.makedirs(OUT_DIR, exist_ok=True)
    text = build_kernel(models, args.limit)
    # Compile what we generated before Kaggle ever sees it: a stray quote in
    # the runner template used to burn a whole push with a SyntaxError in the
    # remote log, which is slow to diagnose and wastes the GPU quota.
    try:
        compile(text, OUT_KERNEL, "exec")
    except SyntaxError as exc:
        print("GENERATED KERNEL IS NOT VALID PYTHON: %s (line %s)"
              % (exc.msg, exc.lineno))
        tail = text.splitlines()[max(0, (exc.lineno or 1) - 3):(exc.lineno or 1) + 2]
        for line in tail:
            print("    " + line)
        return 1
    with open(OUT_KERNEL, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(OUT_META, "w", encoding="utf-8", newline="\n") as f:
        json.dump(build_meta(models, args.slug), f, indent=2)
        f.write("\n")
    print("wrote %s (%d bytes, models=%s, limit=%s)"
          % (OUT_KERNEL, len(text), ",".join(models), args.limit or "full"))
    print("wrote %s" % OUT_META)
    return 0


if __name__ == "__main__":
    sys.exit(main())
