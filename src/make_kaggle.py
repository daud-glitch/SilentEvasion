"""
Generate a self-contained Kaggle kernel that runs the whole study unattended.

Why Kaggle instead of Colab: `kaggle kernels push` runs a script on a free GPU
(2x T4, ~30 h/week) and `kaggle kernels output` pulls the results back, so the
run needs no notebook cells, no pasting, and no human in the loop. Colab has no
equivalent on Windows (its CLI is Linux/macOS only).

    python src/make_kaggle.py                     # qwen2.5-3b, full 800 rows
    python src/make_kaggle.py --models qwen2.5-3b,smollm2-1.7b

Then:
    python src/kaggle_push.py --wait              # push, poll, download

The kernel embeds colab_bootstrap.py verbatim (guard removed), so the remote VM
rebuilds every source file, downloads the datasets, rebuilds the frozen splits,
and then runs probe -> baseline -> gate -> eligibility without any upload.
"""
