"""
Generate `colab_bootstrap.py`: one self-contained cell that rebuilds the whole
project in a fresh runtime (no zip upload, no "No such file or directory").

It embeds every src/*.py and tests/*.py as a gzip+base64 tar with per-file
sha256, plus the expected split fingerprints. Running the cell then:

  1. writes all source files into the project root and verifies their hashes
  2. byte-compiles them (catches a truncated copy immediately)
  3. downloads + curates the datasets, only if data/processed/ is missing
  4. rebuilds results/eval_subset.csv and results/attack_ch1_input.csv and
     checks they are the SAME splits every other run used
  5. prints the next commands to run

Regenerate after editing anything in src/ or tests/:

    python src/make_bootstrap.py

`tests/check_bootstrap.py` fails if this file is stale, so a forgotten
regeneration cannot silently ship an old version of a fix.
"""
import base64
import gzip
import hashlib
import io
import os
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "colab_bootstrap.py")

TEMPLATE = r'''#!/usr/bin/env python3
"""SLM robustness - fresh-runtime bootstrap (@@GENERATED@@).

Generated by src/make_bootstrap.py - do not hand-edit; regenerate instead.

Paste this whole file into ONE Colab cell and run it, or:

    %run /content/colab_bootstrap.py

It recreates every source file, rebuilds the datasets and the frozen splits,
and tells you what to run next. Safe to re-run: existing data is reused.

Environment switches:
    SLM_ROOT=/content     project root (default /content)
    SLM_SKIP_DATA=1       never touch datasets, only restore code
"""
import base64
import gzip
import hashlib
import io
import os
import subprocess
import sys
import tarfile

ROOT = os.path.abspath(os.environ.get("SLM_ROOT", "/content"))
SKIP_DATA = os.environ.get("SLM_SKIP_DATA", "0") == "1"

PAYLOAD_B64 = (
@@PAYLOAD@@
)

FILES_SHA256 = {
@@MANIFEST@@
}

# Results that must come out identical on every machine, or the numbers are
# not comparable with earlier runs.
EXPECTED_SPLITS = {
@@SPLITS@@
}

DATA_FILES = ["data/processed/sms_smishing.csv", "data/processed/phishing_email.csv"]
REQUIRED = ["pandas", "numpy", "sklearn", "requests", "tqdm"]
SERVER = ["fastapi", "uvicorn", "transformers", "torch"]


def unpack():
    """Write every embedded file into ROOT and verify its sha256."""
    blob = gzip.decompress(base64.b64decode(PAYLOAD_B64))
    tar = tarfile.open(fileobj=io.BytesIO(blob))
    written, bad = [], []
    for member in tar.getmembers():
        if not member.isfile():
            continue
        rel = member.name
        if rel.startswith("/") or ".." in rel.split("/"):
            raise RuntimeError("unsafe path in payload: %s" % rel)
        data = tar.extractfile(member).read()
        dest = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "wb") as f:
            f.write(data)
        want = FILES_SHA256.get(rel)
        if want is None:
            bad.append(rel + " (not in manifest)")
        elif hashlib.sha256(data).hexdigest() != want:
            bad.append(rel + " (sha256 mismatch)")
        written.append(rel)
    missing = sorted(set(FILES_SHA256) - set(written))
    return written, bad, missing


def syntax_check():
    import compileall
    ok = True
    for sub in ("src", "tests"):
        d = os.path.join(ROOT, sub)
        if os.path.isdir(d) and not compileall.compile_dir(d, quiet=1, force=True):
            ok = False
    return ok


def ensure_data():
    if SKIP_DATA:
        print("[data] skipped (SLM_SKIP_DATA=1)")
        return True
    missing = [p for p in DATA_FILES if not os.path.exists(os.path.join(ROOT, p))]
    if not missing:
        print("[data] processed datasets present, reusing them")
        return True
    print("[data] missing %s -> downloading (~55 MB, 1-3 min)" % missing)
    r = subprocess.run([sys.executable, "src/prepare_data.py"], cwd=ROOT)
    if r.returncode != 0:
        print("[data] FAILED. Upload data/raw/SMSSpamCollection and "
              "data/raw/phishing_raw.csv, then re-run this cell.")
        return False
    return True


def rebuild_splits():
    sys.path.insert(0, ROOT)
    from src.build_splits import build, fingerprint, write
    ev, at, cal = build()
    write(ev, at, cal)
    ok = True
    for path, df in (("results/eval_subset.csv", ev),
                     ("results/attack_ch1_input.csv", at),
                     ("results/calibration_subset.csv", cal)):
        if not len(df):
            continue
        got = fingerprint(df)
        want = EXPECTED_SPLITS[path]
        print("[splits] %-22s n=%-4d %s  %s"
              % (os.path.basename(path), len(df), got[:16],
                 "OK" if got == want else "DRIFT"))
        if got != want:
            ok = False
            print("         expected %s - dataset or pandas version differs, "
                  "results will not be comparable" % want[:16])
    return ok


def check_deps():
    import importlib.util
    missing = [m for m in REQUIRED + SERVER
               if importlib.util.find_spec(m) is None]
    if missing:
        print("[deps] missing: %s" % ", ".join(missing))
        print("       !pip -q install %s" % " ".join(missing))
    else:
        print("[deps] pandas/numpy/sklearn/requests/tqdm + server stack present")
    return [m for m in REQUIRED if m in missing]


def main():
    print("== SLM robustness bootstrap == root=%s" % ROOT)
    os.makedirs(ROOT, exist_ok=True)
    os.chdir(ROOT)

    written, bad, missing = unpack()
    print("[files] wrote %d files" % len(written))
    if bad:
        for b in bad:
            print("        BAD %s" % b)
    if missing:
        for m in missing:
            print("        MISSING %s" % m)

    code_ok = not bad and not missing
    code_ok = syntax_check() and code_ok
    if not code_ok:
        print("[files] FAILED - payload damaged, regenerate src/make_bootstrap.py")

    hard_deps = check_deps()
    data_ok = ensure_data() if code_ok else False
    if data_ok:
        try:
            splits_ok = rebuild_splits()
        except Exception as exc:
            # A corrupt/partial dataset must end in a readable diagnosis, not a
            # traceback in the middle of a notebook cell.
            print("[splits] ERROR %s: %s" % (type(exc).__name__, exc))
            print("         delete data/processed/ and re-run to re-download")
            splits_ok = False
    else:
        splits_ok = False

    ok = code_ok and data_ok and splits_ok and not hard_deps
    print("-" * 62)
    print("BOOTSTRAP %s: %d files, data=%s, splits=%s"
          % ("OK" if ok else "INCOMPLETE", len(written),
             "ready" if data_ok else "missing",
             "verified" if splits_ok else "unverified"))
    if ok:
        print("""
Next:
    !nohup python src/shim_colab.py > shim.log 2>&1 &
    !sleep 20 && curl -s localhost:8000/health
    !python src/run_baseline.py --model qwen2.5-3b --base-url http://localhost:8000/v1
    !python src/analyze_baseline.py""")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
'''


def collect_files():
    """Every .py under src/ and tests/ - discovered, never hand-listed."""
    files = []
    for sub in ("src", "tests"):
        d = os.path.join(ROOT, sub)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if name.endswith(".py"):
                files.append("%s/%s" % (sub, name))
    if not files:
        raise SystemExit("no source files found under src/ or tests/")
    return files


def build_payload(files):
    """Deterministic tar.gz of the sources (fixed mtime/uid, sorted order)."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as tar:
        for rel in files:
            with open(os.path.join(ROOT, rel), "rb") as f:
                data = f.read()
            info = tarfile.TarInfo(rel)
            info.size = len(data)
            info.mtime = 0
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tar.addfile(info, io.BytesIO(data))
    return base64.b64encode(gzip.compress(buf.getvalue(), 9, mtime=0)).decode("ascii")


def split_fingerprints():
    """Fingerprints of the splits this machine builds (= the study's splits)."""
    sys.path.insert(0, ROOT)
    from src.build_splits import build, fingerprint
    ev, at, cal = build()
    prints = {
        "results/eval_subset.csv": fingerprint(ev),
        "results/attack_ch1_input.csv": fingerprint(at),
    }
    if len(cal):
        prints["results/calibration_subset.csv"] = fingerprint(cal)
    return prints


def render(files, payload, splits):
    manifest = "\n".join(
        '    "%s": "%s",' % (rel, hashlib.sha256(
            open(os.path.join(ROOT, rel), "rb").read()).hexdigest())
        for rel in files)
    wrapped = "\n".join('    "%s"' % payload[i:i + 100]
                        for i in range(0, len(payload), 100))
    split_lines = "\n".join('    "%s": "%s",' % (k, v) for k, v in splits.items())
    # Stamp = hash of the payload, so the file says exactly which sources it
    # carries and regenerating is reproducible (no timestamps, no git state).
    stamp = hashlib.sha256(payload.encode("ascii")).hexdigest()[:12]
    return (TEMPLATE
            .replace("@@GENERATED@@", "payload %s, %d files"
                     % (stamp, len(files)))
            .replace("@@PAYLOAD@@", wrapped)
            .replace("@@MANIFEST@@", manifest)
            .replace("@@SPLITS@@", split_lines))


def main():
    files = collect_files()
    payload = build_payload(files)
    splits = split_fingerprints()
    text = render(files, payload, splits)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes, %d files embedded, payload %d b64 chars)"
          % (OUT, len(text), len(files), len(payload)))
    print("splits:", splits)
    return 0


if __name__ == "__main__":
    sys.exit(main())
